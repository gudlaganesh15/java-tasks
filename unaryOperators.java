public class unaryOperators {
    public static void main(String[] args) {
        int a = 50;
        System.out.println("==========Unary Operators==========");
        System.out.println("a++: " + (a++));
        System.out.println("++a: " + (++a));
        System.out.println("a--: " + (a--));
        System.out.println("--a: " + (--a));
    }
}
